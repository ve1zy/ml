import streamlit as st
import pandas as pd
import os

st.title("📁 О наборе данных")

task = st.selectbox("Выберите задачу:", [
    "Регрессия: Предсказание цены авто (cars)",
    "Классификация: Диагностика диабета (diabetes)"
])

is_regression = "Регрессия" in task

if is_regression:
    st.header("Датасет: Cars (Прогнозирование цены автомобиля)")
    
    col1, col2 = st.columns(2)
    with col1:
        st.markdown("""
        **Целевая переменная:** `price_usd` — цена автомобиля в долларах США.

        **Признаки:**
        | Признак | Описание | Тип |
        |---|---|---|
        | `brand` | Марка автомобиля | категориальный |
        | `model` | Модель автомобиля | категориальный |
        | `year` | Год выпуска | числовой |
        | `mileage` | Пробег в км | числовой |
        | `engine_capacity` | Объём двигателя (л) | числовой |
        | `transmission` | Тип КПП | категориальный |
        | `body_type` | Тип кузова | категориальный |
        | `fuel_type` | Тип топлива | категориальный |
        | `color` | Цвет кузова | категориальный |
        | `doors` | Количество дверей | числовой |

        **Задача:** Регрессия — предсказание цены автомобиля на основе его характеристик.
        """)
    with col2:
        if os.path.exists("data/cars.csv"):
            df = pd.read_csv("data/cars.csv")
            st.subheader("Первые 5 строк")
            st.dataframe(df.head(), use_container_width=True)
            st.success(f"Размер датасета: {df.shape[0]} строк × {df.shape[1]} столбцов")
    
    st.markdown("""
    ### Предобработка данных:
    1. Удаление пропущенных значений (dropna)
    2. One-Hot Encoding для категориальных признаков
    3. StandardScaler для числовых признаков
    4. Разделение на train/test (80/20)

    ### EDA — особенности:
    - Сильная корреляция между `year`, `mileage` и `price_usd`
    - Люксовые бренды (BMW, Mercedes, Audi) имеют значительно более высокие цены
    - Электрокары и гибриды получают премию к стоимости
    - Пробег имеет практически линейную отрицательную зависимость от цены
    """)
    
else:
    st.header("Датасет: Diabetes (Диагностика диабета)")
    
    col1, col2 = st.columns(2)
    with col1:
        st.markdown("""
        **Целевая переменная:** `Diabetes_012`
        - `0` — нет диабета
        - `1` — преддиабет
        - `2` — диабет

        **Признаки (21 признак):**
        | Признак | Описание |
        |---|---|
        | `HighBP` | Высокое давление (0/1) |
        | `HighChol` | Высокий холестерин (0/1) |
        | `BMI` | Индекс массы тела (15-55) |
        | `Smoker` | Курение (0/1) |
        | `Stroke` | Инсульт в анамнезе (0/1) |
        | `HeartDiseaseorAttack` | Болезни сердца (0/1) |
        | `PhysActivity` | Физическая активность (0/1) |
        | `GenHlth` | Общее здоровье (1-5) |
        | `Age` | Возрастная группа (1-13) |
        | `Education` | Уровень образования (1-6) |
        | `Income` | Уровень дохода (1-8) |

        **Задача:** Многоклассовая классификация — определение состояния пациента.
        """)
    with col2:
        if os.path.exists("data/diabetes.csv"):
            df = pd.read_csv("data/diabetes.csv")
            st.subheader("Первые 5 строк")
            st.dataframe(df.head(), use_container_width=True)
            st.success(f"Размер датасета: {df.shape[0]} строк × {df.shape[1]} столбцов")
    
    st.markdown("""
    ### Предобработка данных:
    1. Удаление пропусков
    2. StandardScaler для всех числовых признаков
    3. Stratified split для сохранения пропорций классов

    ### EDA — особенности:
    - Классы несбалансированы (класс 0 преобладает)
    - BMI и высокое давление — главные факторы риска
    - Возраст коррелирует с наличием диабета
    - Низкий доход и физическая неактивность повышают риск
    """)
